"""Figure 2: share of derived memories erased vs. forget rate, measured (markers) and predicted by the
fan-in law 1-(1-p)^f averaged over the measured fan-in distribution (lines). Sound rule, LoCoMo conv. 0-1.
Usage: python3 -I eval/make_figures.py --res results --out ../manuscrit/fig_radius.pdf
"""
import argparse, json
import numpy as np
try:
    import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
except ImportError:   # pgfplots output only
    plt = None

PAL = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4"]   # validated categorical slots 1-5
MARK = ["o", "s", "^", "D", "v"]

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--res", default="results"); ap.add_argument("--out", default="../manuscrit/fig_radius.pdf")
    a = ap.parse_args(); R = json.load(open(f"{a.res}/results_radius.json"))
    series = [("session_writer_conv0-1", "Session writer")] + [(f"window{w}_writer_conv0-1", f"{w}-turn windows") for w in (16, 8, 4, 2)]
    series = [(k, l) for k, l in series if k in R]
    if plt is None:
        write_pgfplots(R, series, a.out.replace(".pdf", "_pgf.tex")); return
    plt.rcParams.update({"font.family": "serif", "font.size": 8, "axes.spines.top": False, "axes.spines.right": False})
    fig, ax = plt.subplots(figsize=(3.45, 2.35))
    p = np.linspace(0, 0.10, 101)
    for i, (k, lab) in enumerate(series):
        d = R[k]["sound"]; h = {int(f): c for f, c in d["fan_hist"].items()}
        f = np.array(list(h)); w = np.array(list(h.values()), float); w /= w.sum()
        pred = np.array([(w * (1 - (1 - x) ** f)).sum() for x in p])
        ax.plot(100 * p, 100 * pred, color=PAL[i], lw=1.2, alpha=0.9)
        xs = [1, 5, 10]; ys = [100 * d[f"erased@{x/100}"] for x in (1, 5, 10)]
        ax.plot(xs, ys, MARK[i], color=PAL[i], ms=4.5, mec="white", mew=0.6, clip_on=False,
                label=f"{lab} ($\\bar f$={d['mean_source_ancestors']:.0f})")
    ax.set_xlabel("Turns forgotten (%)"); ax.set_ylabel("Derived memories erased (%)")
    ax.set_xlim(0, 10); ax.set_ylim(0, 102); ax.grid(axis="y", color="#e6e6e3", lw=0.6); ax.set_axisbelow(True)
    from matplotlib.lines import Line2D
    h, l = ax.get_legend_handles_labels()
    h += [Line2D([], [], color="#555555", marker="o", ls="", ms=4), Line2D([], [], color="#555555", lw=1.2)]
    l += ["measured (3 seeds)", "predicted $1-(1-p)^f$"]
    ax.legend(h, l, frameon=False, fontsize=6.3, loc="upper left", bbox_to_anchor=(0.30, 0.86), handletextpad=0.4, labelspacing=0.35)
    fig.tight_layout(); fig.savefig(a.out, bbox_inches="tight"); fig.savefig(a.out.replace(".pdf", ".png"), dpi=200, bbox_inches="tight")
    write_pgfplots(R, series, a.out.replace(".pdf", "_pgf.tex"))

def write_pgfplots(R, series, out):
    """Same figure as pgfplots source (text only, so that it can live in a single-file Overleaf manuscript)."""
    cols = ["2A78D6", "EB6834", "1BAF7A", "EDA100", "E87BA4"]; marks = ["*", "square*", "triangle*", "diamond*", "pentagon*"]
    L = ["% generated by code/eval/make_figures.py -- do not edit",
         "\\begin{tikzpicture}\\begin{axis}[width=\\columnwidth, height=0.68\\columnwidth, xmin=0, xmax=10, ymin=0, ymax=102,",
         "  xlabel={Turns forgotten (\\%)}, ylabel={Derived memories erased (\\%)}, tick label style={font=\\scriptsize},",
         "  label style={font=\\footnotesize}, ymajorgrids, grid style={black!10}, axis lines=left,",
         "  legend style={font=\\tiny, draw=none, fill=none, at={(0.5,-0.28)}, anchor=north, legend columns=2, column sep=4pt, row sep=-1pt}, legend cell align=left]"]
    p = np.linspace(0, 0.10, 41)
    for i, (k, lab) in enumerate(series):
        d = R[k]["sound"]; h = {int(f): c for f, c in d["fan_hist"].items()}
        f = np.array(list(h)); w = np.array(list(h.values()), float); w /= w.sum()
        L.append(f"\\definecolor{{c{i}}}{{HTML}}{{{cols[i]}}}")
        pred = " ".join(f"({100*x:.1f},{100*(w * (1 - (1 - x) ** f)).sum():.2f})" for x in p)
        L.append(f"\\addplot[c{i}, thick, forget plot] coordinates {{{pred}}};")
        meas = " ".join(f"({x},{100 * d[f'erased@{x/100}']:.2f})" for x in (1, 5, 10))
        L.append(f"\\addplot[only marks, mark={marks[i]}, mark size=1.8pt, c{i}, mark options={{draw=white, line width=0.3pt}}] "
                 f"coordinates {{{meas}}};")
        L.append(f"\\addlegendentry{{{lab} ($\\bar f$={d['mean_source_ancestors']:.0f})}}")
    L += ["\\addlegendimage{only marks, mark=*, black!65}\\addlegendentry{measured (3 seeds)}",
          "\\addlegendimage{black!65, thick}\\addlegendentry{predicted $1-(1-p)^f$}",
          "\\end{axis}\\end{tikzpicture}"]
    open(out, "w").write("\n".join(L) + "\n")

if __name__ == "__main__":
    main()
